assert.doesNotMatch(page, /b\.status!==\"draft\"[\s\S]{0,120}Edit/);
assert.match(page, /min-w-\[1750px\]/);
assert.match(page, /label\(/);
assert.match(page, /const counts=/);
assert.match(page, /counts\.draft/);
assert.match(page, /counts\.pending/);
