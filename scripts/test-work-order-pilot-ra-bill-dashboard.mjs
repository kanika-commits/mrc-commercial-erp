assert.doesNotMatch(route, /\.eq\("status", "rejected"\)/);
assert.match(page, /href=\{\"\/forms\/pilot\/ra-bills\/\"\+b\.id\}/);
assert.match(page, /b\.status===\"draft\"&&<Link aria-label=\{\"Edit /);
