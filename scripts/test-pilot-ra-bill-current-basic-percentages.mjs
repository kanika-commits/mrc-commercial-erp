const editable = (value) => {
  const sanitized = value.replace(/,/g, "").replace(/[^0-9.]/g, "");
  const [whole = "", ...decimals] = sanitized.split(".");
  const normalized = whole.replace(/^0+(?=\d)/, "");
  return decimals.length ? `${normalized}.${decimals.join("").slice(0, 2)}` : normalized;
};
assert.equal(editable(editable("328") + "3"), "3283");
