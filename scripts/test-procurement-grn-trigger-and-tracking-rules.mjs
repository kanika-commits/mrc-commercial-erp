function expectedSlipTime(value) {
  const match = String(value).trim().replace(/[.\s]+/g, ":").match(/^([01]?\d|2[0-3]):([0-5]\d)(?::([0-5]\d))?$/);
  return match ? `${match[1].padStart(2, "0")}:${match[2]}` : null;
}
