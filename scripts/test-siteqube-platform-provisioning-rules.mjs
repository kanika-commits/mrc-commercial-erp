import assert from "node:assert/strict";
import fs from "node:fs";
const helper = fs.readFileSync("lib/platformProvisioning.ts", "utf8");
const route = fs.readFileSync("app/api/platform/organizations/provision/validate/route.ts", "utf8");
const wizard = fs.readFileSync("app/platform/organizations/new/page.tsx", "utf8");
const server = fs.readFileSync("lib/platformProvisioningServer.ts", "utf8");
const provisionRoute = fs.readFileSync("app/api/platform/organizations/provision/route.ts", "utf8");
assert.match(helper, /ManagedTenantProvisioningInput|organization/, "Typed provisioning contract exists");
assert.match(helper, /STANDARD_MODULES/, "Allowed modules are explicit");
assert.match(helper, /infrastructure !== "standard"/, "Enterprise infrastructure is rejected");
assert.match(helper, /reserved/, "Reserved slugs are rejected");
assert.match(helper, /invite_required/, "Tenant admin remains invite-based");
assert.match(route, /requirePlatformOwner/, "Validation is Platform Owner protected");
assert.match(route, /export async function POST/, "Validation endpoint is POST");
assert.match(route, /organization_domains/, "Slug and hostname uniqueness are checked");
assert.doesNotMatch(route, /\.insert\(|\.update\(|\.upsert\(|\.delete\(|auth\.admin/, "Validation endpoint performs no writes or Auth operations");
assert.doesNotMatch(route, /organization_id.*body|body.*organization_id|membership_id|role_id|isPlatformOwner/, "Client cannot supply authority or ownership IDs");
assert.match(wizard, /Provision Organization/, "Wizard final action remains present");
assert.match(wizard, /fetch\("\/api\/platform\/organizations\/provision"/, "Wizard submits through the provisioning API");
assert.match(wizard, /submitting/, "Wizard prevents duplicate submissions and shows progress");
assert.match(server, /requirePlatformOwner/, "Provisioning service verifies Platform Owner server-side");
assert.match(server, /SITEQUBE_PROVISIONING_ENABLED/, "Provisioning service is feature-gated");
assert.match(provisionRoute, /provisionManagedOrganization/, "Provision route uses the server-only service");
console.log("SiteQube Platform Phase 4A provisioning rules: PASS");
