import assert from "node:assert/strict";
import fs from "node:fs";
const approvalApi = fs.readFileSync("app/api/approvals/work-orders/route.ts", "utf8");
const workOrderApi = fs.readFileSync("app/api/work-orders/[id]/route.ts", "utf8");
const registerApi = fs.readFileSync("app/api/work-orders/register/route.ts", "utf8");
const formsPage = fs.readFileSync("app/work-orders/page.tsx", "utf8");
const draftHelper = fs.readFileSync("lib/serverWorkOrderDraft.ts", "utf8");
const draftApi = fs.readFileSync("app/api/work-orders/drafts/[id]/route.ts", "utf8");
assert.match(approvalApi, /eq\("approval_status", "pending"\)/);
assert.doesNotMatch(approvalApi, /approval_status\.is\.null/);
assert.match(workOrderApi, /update\(\{ approval_status: "sent_back" \}\)/);
assert.match(draftHelper, /in\("approval_status", \["draft", "sent_back"\]\)/);
assert.match(draftHelper, /Only the Work Order creator can edit a sent-back Work Order/);
assert.match(draftApi, /approval_status: action \? "pending" : \(result\.data\.approval_status === "sent_back" \? "sent_back" : "draft"\)/);
assert.match(registerApi, /approval_status\.in\.\(draft,pending,approved,sent_back\)/);
assert.match(registerApi, /in\("action", \["reject", "send_back"\]\)/);
assert.match(registerApi, /canonicalAction|canonical_action/);
assert.match(registerApi, /sent_back_comment: latestSendBackComments\.get\(row\.id\)/);
assert.match(formsPage, /sent_back_comment && <p className="mt-2 max-w-\[260px\] text-xs text-red-700">↳ \{wo\.sent_back_comment\}<\/p>/);
const row = { id: "wo-lnmiit-pi-1127", wo_number: "LNMIIT/PI/1127", approval_status: "sent_back", sent_back_comment: "Please correct the Daily Wage details." };
const pending = { id: "other-pending", approval_status: "pending" };
assert.equal(row.sent_back_comment, "Please correct the Daily Wage details.");
assert.deepEqual([row, pending].filter((item) => item.approval_status === "pending").map((item) => item.id), ["other-pending"]);
console.log("Local Work Order send-back status/comment regression passed");
